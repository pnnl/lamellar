#!/usr/bin/env python3
"""Generates shmem.h. Keep the type tables in sync with the macro invocations in src/*.rs
(run tests/check_header.sh to verify every declared symbol is exported by libshmem)."""
import sys

RMA = [("float", "float"), ("double", "double"), ("char", "char"), ("schar", "signed char"),
       ("short", "short"), ("int", "int"), ("long", "long"), ("longlong", "long long"),
       ("uchar", "unsigned char"), ("ushort", "unsigned short"), ("uint", "unsigned int"),
       ("ulong", "unsigned long"), ("ulonglong", "unsigned long long"),
       ("int8", "int8_t"), ("int16", "int16_t"), ("int32", "int32_t"), ("int64", "int64_t"),
       ("uint8", "uint8_t"), ("uint16", "uint16_t"), ("uint32", "uint32_t"), ("uint64", "uint64_t"),
       ("size", "size_t"), ("ptrdiff", "ptrdiff_t")]
AMO = [("int", "int"), ("long", "long"), ("longlong", "long long"), ("uint", "unsigned int"),
       ("ulong", "unsigned long"), ("ulonglong", "unsigned long long"), ("int32", "int32_t"),
       ("int64", "int64_t"), ("uint32", "uint32_t"), ("uint64", "uint64_t"),
       ("size", "size_t"), ("ptrdiff", "ptrdiff_t")]
WAIT = [("short", "short"), ("int", "int"), ("long", "long"), ("longlong", "long long"),
        ("ushort", "unsigned short"), ("uint", "unsigned int"), ("ulong", "unsigned long"),
        ("ulonglong", "unsigned long long"), ("int32", "int32_t"), ("int64", "int64_t"),
        ("uint32", "uint32_t"), ("uint64", "uint64_t"), ("size", "size_t"), ("ptrdiff", "ptrdiff_t")]
# Fixed-width and size_t/ptrdiff_t alias these on LP64; they are callable by name only.
G_RMA = ["float", "double", "char", "schar", "short", "int", "long", "longlong", "uchar",
         "ushort", "uint", "ulong", "ulonglong"]
G_AMO = ["int", "long", "longlong", "uint", "ulong", "ulonglong"]
G_WAIT = ["short", "int", "long", "longlong", "ushort", "uint", "ulong", "ulonglong"]
CT = dict(RMA + AMO + WAIT)
RED_INT = [("short", "short"), ("int", "int"), ("long", "long"), ("longlong", "long long")]
RED_FP = [("float", "float"), ("double", "double")]

o = []
w = o.append
w("""/* Generated by include/gen_shmem_h.py -- do not edit. OpenSHMEM 1.4 API for Lamellar. */
#ifndef SHMEM_H
#define SHMEM_H
#include <stddef.h>
#include <stdint.h>
#ifdef __cplusplus
extern "C" {
#endif

#define SHMEM_MAJOR_VERSION 1
#define SHMEM_MINOR_VERSION 4
#define _SHMEM_MAJOR_VERSION 1
#define _SHMEM_MINOR_VERSION 4
#define SHMEM_VENDOR_STRING "Lamellar OpenSHMEM"
#define SHMEM_MAX_NAME_LEN 256

#define SHMEM_THREAD_SINGLE 0
#define SHMEM_THREAD_FUNNELED 1
#define SHMEM_THREAD_SERIALIZED 2
#define SHMEM_THREAD_MULTIPLE 3

#define SHMEM_SYNC_VALUE (-1L)
/* pSync/pWrk are accepted but unused (internal synchronization), so sizes only need to
   be large enough for applications that size arrays with these constants. */
#define SHMEM_BARRIER_SYNC_SIZE 64
#define SHMEM_BCAST_SYNC_SIZE 64
#define SHMEM_COLLECT_SYNC_SIZE 64
#define SHMEM_REDUCE_SYNC_SIZE 64
#define SHMEM_REDUCE_MIN_WRKDATA_SIZE 64
#define _SHMEM_SYNC_VALUE SHMEM_SYNC_VALUE
#define _SHMEM_BARRIER_SYNC_SIZE SHMEM_BARRIER_SYNC_SIZE
#define _SHMEM_BCAST_SYNC_SIZE SHMEM_BCAST_SYNC_SIZE
#define _SHMEM_COLLECT_SYNC_SIZE SHMEM_COLLECT_SYNC_SIZE
#define _SHMEM_REDUCE_SYNC_SIZE SHMEM_REDUCE_SYNC_SIZE
#define _SHMEM_REDUCE_MIN_WRKDATA_SIZE SHMEM_REDUCE_MIN_WRKDATA_SIZE

#define SHMEM_CMP_EQ 0
#define SHMEM_CMP_NE 1
#define SHMEM_CMP_GT 2
#define SHMEM_CMP_LE 3
#define SHMEM_CMP_LT 4
#define SHMEM_CMP_GE 5
#define _SHMEM_CMP_EQ SHMEM_CMP_EQ
#define _SHMEM_CMP_NE SHMEM_CMP_NE
#define _SHMEM_CMP_GT SHMEM_CMP_GT
#define _SHMEM_CMP_LE SHMEM_CMP_LE
#define _SHMEM_CMP_LT SHMEM_CMP_LT
#define _SHMEM_CMP_GE SHMEM_CMP_GE

/* setup, queries */
void shmem_init(void);
int shmem_init_thread(int requested, int *provided);
void shmem_query_thread(int *provided);
void start_pes(int npes);
void shmem_finalize(void);
void shmem_global_exit(int status);
int shmem_my_pe(void);
int shmem_n_pes(void);
int _my_pe(void);
int _num_pes(void);
int shmem_pe_accessible(int pe);
int shmem_addr_accessible(const void *addr, int pe);
void *shmem_ptr(const void *dest, int pe);
void shmem_info_get_version(int *major, int *minor);
void shmem_info_get_name(char *name);

/* memory management */
void *shmem_malloc(size_t size);
void *shmem_calloc(size_t count, size_t size);
void *shmem_realloc(void *ptr, size_t size);
void *shmem_align(size_t alignment, size_t size);
void shmem_free(void *ptr);
void *shmalloc(size_t size);
void *shrealloc(void *ptr, size_t size);
void *shmemalign(size_t alignment, size_t size);
void shfree(void *ptr);

/* ordering, synchronization */
void shmem_quiet(void);
void shmem_fence(void);
void shmem_barrier_all(void);
void shmem_sync_all(void);
void shmem_barrier(int PE_start, int logPE_stride, int PE_size, long *pSync);
void shmem_sync(int PE_start, int logPE_stride, int PE_size, long *pSync);

/* untyped and sized RMA */
void shmem_putmem(void *dest, const void *src, size_t nbytes, int pe);
void shmem_getmem(void *dest, const void *src, size_t nbytes, int pe);
void shmem_putmem_nbi(void *dest, const void *src, size_t nbytes, int pe);
void shmem_getmem_nbi(void *dest, const void *src, size_t nbytes, int pe);
""")
for b in (8, 16, 32, 64, 128):
    for op in ("put", "get"):
        for nbi in ("", "_nbi"):
            w(f"void shmem_{op}{b}{nbi}(void *dest, const void *src, size_t nelems, int pe);")

w("\n/* typed RMA */")
for n, t in RMA:
    w(f"void shmem_{n}_put({t} *dest, const {t} *src, size_t nelems, int pe);")
    w(f"void shmem_{n}_get({t} *dest, const {t} *src, size_t nelems, int pe);")
    w(f"void shmem_{n}_put_nbi({t} *dest, const {t} *src, size_t nelems, int pe);")
    w(f"void shmem_{n}_get_nbi({t} *dest, const {t} *src, size_t nelems, int pe);")
    w(f"void shmem_{n}_p({t} *dest, {t} value, int pe);")
    w(f"{t} shmem_{n}_g(const {t} *src, int pe);")
    w(f"void shmem_{n}_iput({t} *dest, const {t} *src, ptrdiff_t dst, ptrdiff_t sst, size_t nelems, int pe);")
    w(f"void shmem_{n}_iget({t} *dest, const {t} *src, ptrdiff_t dst, ptrdiff_t sst, size_t nelems, int pe);")

w("\n/* atomics */")
for n, t in AMO:
    w(f"{t} shmem_{n}_atomic_fetch(const {t} *src, int pe);")
    w(f"void shmem_{n}_atomic_set({t} *dest, {t} value, int pe);")
    w(f"{t} shmem_{n}_atomic_swap({t} *dest, {t} value, int pe);")
    w(f"{t} shmem_{n}_atomic_compare_swap({t} *dest, {t} cond, {t} value, int pe);")
    w(f"{t} shmem_{n}_atomic_fetch_inc({t} *dest, int pe);")
    w(f"void shmem_{n}_atomic_inc({t} *dest, int pe);")
    for op in ("add", "and", "or", "xor"):
        w(f"{t} shmem_{n}_atomic_fetch_{op}({t} *dest, {t} value, int pe);")
        w(f"void shmem_{n}_atomic_{op}({t} *dest, {t} value, int pe);")
    w(f"void shmem_{n}_atomic_fetch_nbi({t} *fetch, const {t} *src, int pe);")
    w(f"void shmem_{n}_atomic_swap_nbi({t} *fetch, {t} *dest, {t} value, int pe);")
    w(f"void shmem_{n}_atomic_compare_swap_nbi({t} *fetch, {t} *dest, {t} cond, {t} value, int pe);")
    w(f"void shmem_{n}_atomic_fetch_inc_nbi({t} *fetch, {t} *dest, int pe);")
    for op in ("add", "and", "or", "xor"):
        w(f"void shmem_{n}_atomic_fetch_{op}_nbi({t} *fetch, {t} *dest, {t} value, int pe);")
w("\n/* deprecated atomics */")
for n, t in (("int", "int"), ("long", "long"), ("longlong", "long long")):
    w(f"{t} shmem_{n}_fadd({t} *dest, {t} value, int pe);")
    w(f"{t} shmem_{n}_finc({t} *dest, int pe);")
    w(f"void shmem_{n}_add({t} *dest, {t} value, int pe);")
    w(f"void shmem_{n}_inc({t} *dest, int pe);")
    w(f"{t} shmem_{n}_cswap({t} *dest, {t} cond, {t} value, int pe);")
    w(f"{t} shmem_{n}_swap({t} *dest, {t} value, int pe);")
    w(f"{t} shmem_{n}_fetch(const {t} *src, int pe);")
    w(f"void shmem_{n}_set({t} *dest, {t} value, int pe);")
    w(f"void shmem_{n}_wait({t} *ivar, {t} cmp_value);")
w("void shmem_short_wait(short *ivar, short cmp_value);")

w("\n/* point-to-point sync */")
for n, t in WAIT:
    w(f"void shmem_{n}_wait_until({t} *ivar, int cmp, {t} cmp_value);")
    w(f"int shmem_{n}_test({t} *ivar, int cmp, {t} cmp_value);")

w("""
/* locks */
void shmem_set_lock(long *lock);
void shmem_clear_lock(long *lock);
int shmem_test_lock(long *lock);

/* collectives */
void shmem_broadcast32(void *target, const void *source, size_t nlong, int PE_root, int PE_start, int logPE_stride, int PE_size, long *pSync);
void shmem_broadcast64(void *target, const void *source, size_t nlong, int PE_root, int PE_start, int logPE_stride, int PE_size, long *pSync);
void shmem_collect32(void *target, const void *source, size_t nlong, int PE_start, int logPE_stride, int PE_size, long *pSync);
void shmem_collect64(void *target, const void *source, size_t nlong, int PE_start, int logPE_stride, int PE_size, long *pSync);
void shmem_fcollect32(void *target, const void *source, size_t nlong, int PE_start, int logPE_stride, int PE_size, long *pSync);
void shmem_fcollect64(void *target, const void *source, size_t nlong, int PE_start, int logPE_stride, int PE_size, long *pSync);
""")
for n, t in RED_INT:
    for op in ("and", "or", "xor", "max", "min", "sum", "prod"):
        w(f"void shmem_{n}_{op}_to_all({t} *dest, const {t} *source, int nreduce, int PE_start, int logPE_stride, int PE_size, {t} *pWrk, long *pSync);")
for n, t in RED_FP:
    for op in ("max", "min", "sum", "prod"):
        w(f"void shmem_{n}_{op}_to_all({t} *dest, const {t} *source, int nreduce, int PE_start, int logPE_stride, int PE_size, {t} *pWrk, long *pSync);")


def generic(name, args, sel, names, suffix, qualified=False):
    """One _Generic dispatch macro: `sel` is the argument whose type picks the overload."""
    cases = []
    for n in names:
        t = CT[n]
        cases.append(f"{t} *: shmem_{n}_{suffix}")
        if qualified:
            cases.append(f"const {t} *: shmem_{n}_{suffix}")
    w(f"#define {name}({args}) _Generic(({sel}), " + ", ".join(cases) + f")({args})")


w("\n#if !defined(__cplusplus) && defined(__STDC_VERSION__) && __STDC_VERSION__ >= 201112L")
w("/* C11 type-generic interface (fixed-width/size_t/ptrdiff_t alias these on LP64) */")
generic("shmem_put", "dest, src, nelems, pe", "dest", G_RMA, "put")
generic("shmem_get", "dest, src, nelems, pe", "dest", G_RMA, "get")
generic("shmem_put_nbi", "dest, src, nelems, pe", "dest", G_RMA, "put_nbi")
generic("shmem_get_nbi", "dest, src, nelems, pe", "dest", G_RMA, "get_nbi")
generic("shmem_p", "dest, value, pe", "dest", G_RMA, "p")
generic("shmem_g", "src, pe", "src", G_RMA, "g", qualified=True)
generic("shmem_iput", "dest, src, dst, sst, nelems, pe", "dest", G_RMA, "iput")
generic("shmem_iget", "dest, src, dst, sst, nelems, pe", "dest", G_RMA, "iget")
generic("shmem_atomic_fetch", "src, pe", "src", G_AMO, "atomic_fetch", qualified=True)
generic("shmem_atomic_set", "dest, value, pe", "dest", G_AMO, "atomic_set")
generic("shmem_atomic_swap", "dest, value, pe", "dest", G_AMO, "atomic_swap")
generic("shmem_atomic_compare_swap", "dest, cond, value, pe", "dest", G_AMO, "atomic_compare_swap")
generic("shmem_atomic_fetch_inc", "dest, pe", "dest", G_AMO, "atomic_fetch_inc")
generic("shmem_atomic_inc", "dest, pe", "dest", G_AMO, "atomic_inc")
for op in ("add", "and", "or", "xor"):
    generic(f"shmem_atomic_fetch_{op}", "dest, value, pe", "dest", G_AMO, f"atomic_fetch_{op}")
    generic(f"shmem_atomic_{op}", "dest, value, pe", "dest", G_AMO, f"atomic_{op}")
generic("shmem_wait_until", "ivar, cmp, cmp_value", "ivar", G_WAIT, "wait_until")
generic("shmem_test", "ivar, cmp, cmp_value", "ivar", G_WAIT, "test")
w("#endif")
w("""
#ifdef __cplusplus
}
#endif
#endif /* SHMEM_H */""")

out = sys.argv[1] if len(sys.argv) > 1 else "shmem.h"
open(out, "w").write("\n".join(o) + "\n")
